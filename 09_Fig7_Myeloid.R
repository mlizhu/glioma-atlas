## ================================================================
## Myeloid cell downstream analysis
## ================================================================
##
## This script performs downstream analyses of myeloid cells in glioma,
## including myeloid subcluster visualization, cell proportion analysis,
## Ro/e enrichment analysis, BayesPrism-based bulk RNA-seq deconvolution,
## survival analysis, AUCell-based subtype-related gene-set scoring, and
## Monocle2 pseudotime analysis for monocytes/macrophages and microglia.
##
## -------------------------
## Required input files
## -------------------------
##
## 1. Myeloid.rds
##    A processed Seurat object containing annotated myeloid cells.
##    Required metadata columns include:
##      - celltype
##      - group
##      - tumor_type
##    The RNA assay should contain raw count data.
##
## 2. signature.xlsx
##    An Excel file containing subtype-related gene signatures.
##    Required columns include:
##      - IDHWT
##      - IDHMU
##      - Noncodel
##      - Codel
##
## 3. TCGAGBMLGG全数据.xlsx
##    A processed TCGA GBM/LGG bulk RNA-seq expression matrix with
##    survival information. The file should contain overall survival
##    time, survival status, and gene expression values for each sample.
##
## -------------------------
## Main output files
## -------------------------
##
## 1. BayesPrism-inferred myeloid fraction.csv
##    BayesPrism-inferred myeloid subcluster fractions for TCGA GBM/LGG
##    bulk RNA-seq samples, combined with survival metadata.
##
## 2. survival/
##    A folder containing Kaplan-Meier survival plots for each
##    BayesPrism-inferred myeloid subcluster fraction.
##
## 3. TAMacro_GBM_monocle_cds.rds
##    Monocle2 CellDataSet object for monocytes/macrophages in GBM.
##
## 4. TAMacro_AC_monocle_cds.rds
##    Monocle2 CellDataSet object for monocytes/macrophages in astrocytoma.
##
## 5. TAMacro_OD_monocle_cds.rds
##    Monocle2 CellDataSet object for monocytes/macrophages in oligodendroglioma.
##
## 6. MG_GBM_monocle_cds.rds
##    Monocle2 CellDataSet object for microglia in GBM.
##    Microglia cells were downsampled before Monocle2 analysis to ensure
##    computational feasibility.
##
## 7. MG_AC_monocle_cds.rds
##    Monocle2 CellDataSet object for microglia in astrocytoma.
##
## 8. MG_OD_monocle_cds.rds
##    Monocle2 CellDataSet object for microglia in oligodendroglioma.
##
## -------------------------
## Main analyses generated by this script
## -------------------------
##
## 1. Myeloid subcluster visualization.
## 2. Myeloid subcluster proportion analysis across glioma molecular groups.
## 3. Ro/e enrichment analysis of myeloid subclusters across glioma molecular groups.
## 4. BayesPrism-based deconvolution of myeloid subcluster fractions in bulk RNA-seq data.
## 5. Survival analysis based on inferred myeloid subcluster fractions.
## 6. AUCell scoring of subtype-related gene signatures in myeloid cells.
## 7. Monocle2 pseudotime analysis of monocytes/macrophages.
## 8. Monocle2 pseudotime analysis of microglia.
## 9. Pseudotime-associated subtype-related gene-set score visualization.
## ================================================================

