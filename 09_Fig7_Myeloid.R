apportion_largest_remainder <- function(n_vec, target){
  total <- sum(n_vec); raw <- n_vec/total*target
  base <- floor(raw); alloc <- pmin(base, n_vec)
  remain <- target - sum(alloc); frac <- raw - base
  if(remain > 0){
    ord <- order(frac, decreasing = TRUE)
    for(i in ord){ if(remain==0) break
      if(alloc[i] < n_vec[i]){ alloc[i] <- alloc[i] + 1; remain <- remain - 1 }
    }
  } else if(remain < 0){
    ord <- order(frac, decreasing = FALSE)
    for(i in ord){ if(remain==0) break
      if(alloc[i] > 0){ alloc[i] <- alloc[i] - 1; remain <- remain + 1 }
    }
  }
  stopifnot(sum(alloc) == target); alloc
}


