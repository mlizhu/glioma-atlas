library(BayesPrism)
library(survival)
library(survminer)
species = "hs"  
sc.dat <-  as.matrix(t(GetAssayData(Myeloid, assay = "RNA", slot = "counts")))
cell.type.labels<-Myeloid@meta.data$celltype  
cell.state.labels<-NULL   

#1,QC of cell type and state labels
plot.cor.phi (input=sc.dat, 
              input.labels=cell.type.labels, 
              title="cell type correlation",
              cexRow=0.5, cexCol=0.5
)

#2,Filter outlier genes
sc.stat <- plot.scRNA.outlier(
  input=sc.dat, 
  cell.type.labels=cell.type.labels,
  species=species, 
  return.raw=TRUE 
)

sc.dat.filtered <- cleanup.genes (input=sc.dat,
                                  input.type="count.matrix",
                                  species=species, 
                                  gene.group=c( "Rb","Mrp","other_Rb","chrM","MALAT1","chrX","chrY") ,
                                  exp.cells=5)

sc.dat.filtered.pc <-  select.gene.type (sc.dat.filtered,
                                         gene.type = "protein_coding")

exp <- read.xlsx("TCGAGBMLGG全数据.xlsx")
rownames(exp) <- exp[,1]
exp <- exp[,-1]
exp <- as.data.frame(t(exp))

metadata <- exp[,c(4:5)]
names(metadata) <- c("OS.time","OS")
metadata$OS     <- as.numeric (metadata$OS)
metadata$OS.time <- as.numeric (metadata$OS.time)


n <- ncol(exp)
exp<- exp[,c(13:n)]
exp <- as.data.frame(t(exp))
Symbol <- rownames(exp)
Sample  <- names(exp)
exp <- as.data.frame(lapply(exp,as.numeric))
rownames(exp) <- Symbol

bk.dat<-as.matrix(t(exp))

bk.stat <- plot.bulk.outlier(
  bulk.input=bk.dat,
  sc.input=sc.dat, 
  cell.type.labels=cell.type.labels,
  species=species,
  return.raw=TRUE
)

plot.bulk.vs.sc (sc.input = sc.dat.filtered,
                 bulk.input = bk.dat
)

myPrism <- new.prism(
  reference=sc.dat.filtered.pc, 
  mixture=bk.dat,
  input.type="count.matrix", 
  cell.type.labels = cell.type.labels, 
  cell.state.labels = NULL,
  key=NULL,
  outlier.cut=0.01,
  outlier.fraction=0.1)

bp.res <- run.prism(prism = myPrism, n.cores=20)

score <- get.fraction(bp=bp.res,
                      which.theta="final",
                      state.or.type="type")
score <- as.data.frame(score)
score <- rownames_to_column(score, "id")

metadata <- rownames_to_column(metadata, "id")
metadata_score <-left_join(metadata,score,by="id")
write.csv(metadata_score,"BayesPrism-inferred myeloid fraction.csv",row.names = F)


dir.create("survival", showWarnings = FALSE)
for (i in colnames(metadata_score)[4:ncol(metadata_score)]) {
  
  rt <- metadata_score
  med <- median(rt[[i]], na.rm = TRUE)
  rt$group <- ifelse(rt[[i]] > med, "High", "Low")
  rt$group <- factor(rt$group, levels = c("High", "Low"))
  diff <- survdiff(Surv(OS.time, OS) ~ group, data = rt)
  p <- 1 - pchisq(diff$chisq, df = 1)
  
  if (p < 0.0001) {
    pValue <- "p < 0.0001"
  } else {
    pValue <- paste0("p = ", sprintf("%.4f", p))
  }
  
  fit <- survfit(Surv(OS.time, OS) ~ group, data = rt)
  surPlot <- ggsurvplot(
    fit,
    data = rt,
    pval = pValue,
    risk.table = FALSE,
    ggtheme = theme_classic() +
      theme(
        axis.text = element_text(color = "black", size = 7),
        axis.title = element_text(color = "black"),
        panel.grid = element_blank()
      ),
    censor.shape = 124,
    censor.size = 2,
    conf.int = FALSE,
    legend.labs = c("High", "Low"),
    legend.title = i,
    xlab = "Overall survival (months)",
    ylab = "Survival probability",
    palette = c("#E31A1C", "#1F78B4")
  )
  pdf(
    paste0("survival/", i, ".pdf"),
    onefile = FALSE,
    width = 5.5,
    height = 5
  )
  print(surPlot)
  dev.off()
}


